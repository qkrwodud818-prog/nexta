function main() {
  let added = 0;
  let skipped = 0;
  for (const [role, items] of Object.entries(SEED)) {
    const existing = db.getDefaultKnowledge(role).map((k) => k.title);
    for (const item of items) {
      if (existing.includes(item.title)) {
        skipped++;
        continue;
      }
      db.addDefaultKnowledge(role, {
        id: Date.now().toString(36) + Math.random().toString(36).slice(2, 8),
        title: item.title,
        text: item.text,
        addedAt: new Date().toLocaleTimeString("ko-KR", { hour: "2-digit", minute: "2-digit", hour12: true, timeZone: "Asia/Seoul" }),
      });
      added++;
    }
  }
  console.log(`완료 — 새로 추가 ${added}건, 이미 있어서 건너뜀 ${skipped}건`);
}

